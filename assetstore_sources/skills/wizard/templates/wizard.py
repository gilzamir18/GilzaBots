#!/usr/bin/env python3
"""A wizard walks a human through a manual procedure, step by step.

Generated by the `wizard` skill. Standard library only, so it runs wherever
Python does: Windows, macOS, Linux and WSL.

Everything above the "STAGES" marker is the wizard library: do not hand-edit
it. Author the per-step stages in `run_wizard` below the marker.
"""
from __future__ import annotations

import getpass
import os
import shutil
import subprocess
import sys
import tempfile
import webbrowser

# ──────────────────────────────────────────────────────────────────────────
# Wizard library: consistent UX, identical across every wizard.
# ──────────────────────────────────────────────────────────────────────────

# A legacy code page (cp1252 on a Windows pipe) cannot encode ✓ or →: replace
# what it can't print instead of crashing in the middle of a stage.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(errors="replace")
    except (AttributeError, ValueError):
        pass

_COLOUR = sys.stdout.isatty() and os.environ.get("NO_COLOR") is None
if _COLOUR and os.name == "nt":
    os.system("")  # turns on ANSI escape handling in the Windows console


def _style(code: str) -> str:
    return f"\033[{code}m" if _COLOUR else ""


BOLD, DIM, RESET = _style("1"), _style("2"), _style("0")
BLUE, GREEN, YELLOW = _style("34"), _style("32"), _style("33")

TOTAL_STAGES = 0
ENV_FILE = os.environ.get("ENV_FILE", ".env")
_stage_index = 0
WRITTEN_ENV: list[str] = []
WRITTEN_SECRET: list[str] = []
SKIPPED: list[str] = []


def _clear() -> None:
    """Wipe the terminal so only the current step is on screen (no-op when piped)."""
    if sys.stdout.isatty():
        os.system("cls" if os.name == "nt" else "clear")


def banner(title: str) -> None:
    """The opening frame: what this wizard does."""
    _clear()
    print(f"\n{BOLD}{BLUE}  {title}{RESET}")
    print(f"{DIM}  {TOTAL_STAGES} stages{RESET}\n")
    print(f"{DIM}  You drive the browser; this wizard tells you exactly what to do and")
    print("  captures the values you copy back. Stop any time with Ctrl-C and run it")
    print(f"  again later: it remembers the values already saved.{RESET}")
    pause("Ready to start?")


def stage(name: str) -> None:
    """Clear the screen, announce a stage and show the progress."""
    global _stage_index
    _clear()
    _stage_index += 1
    print(f"\n{BOLD}{BLUE}▸ Stage {_stage_index}/{TOTAL_STAGES} · {name}{RESET}")


def say(text: str) -> None:
    print(f"  {text}")


def step(text: str) -> None:
    """An action the human takes, in the browser or elsewhere."""
    print(f"  {BLUE}•{RESET} {text}")


def note(text: str) -> None:
    print(f"  {DIM}{text}{RESET}")


def warn(text: str) -> None:
    print(f"  {YELLOW}⚠ {text}{RESET}")


def open_url(url: str) -> None:
    """Open *url* in the human's browser, on every OS (WSL included)."""
    print(f"  {GREEN}↗ opening{RESET} {url}")
    opened = False
    if "microsoft" in _kernel_release() and shutil.which("wslview"):
        opened = subprocess.run(["wslview", url], capture_output=True).returncode == 0
    if not opened:
        try:
            opened = webbrowser.open(url)
        except webbrowser.Error:
            opened = False
    if not opened:
        warn(f"couldn't open a browser, so visit it manually: {url}")


def _kernel_release() -> str:
    try:
        return os.uname().release.lower()
    except AttributeError:  # Windows
        return ""


def pause(message: str = "Press Enter to continue") -> None:
    """Wait for the human to confirm they've done the manual part."""
    try:
        input(f"  {DIM}{message}{RESET} ")
    except EOFError:
        pass


def confirm(question: str) -> bool:
    """A y/N gate: True on yes."""
    try:
        reply = input(f"  {YELLOW}? {question} [y/N]{RESET} ")
    except EOFError:
        return False
    return reply.strip().lower().startswith("y")


def _existing(key: str) -> str | None:
    """The current value of *key* in ENV_FILE, if any, with its quotes undone."""
    if not os.path.isfile(ENV_FILE):
        return None
    value = None
    with open(ENV_FILE, encoding="utf-8") as handle:
        for line in handle:
            if line.startswith(f"{key}="):
                value = line.rstrip("\n")[len(key) + 1:]
    if value is None:
        return None
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        inner = value[1:-1]
        if value[0] == '"' and any(c in inner for c in '\\$"'):
            return None  # escapes we can't decode safely: ask again
        return inner.replace("'\\''", "'") if value[0] == "'" else inner
    return value


def ask(key: str, prompt: str) -> str:
    """Read a visible (non-secret) value. Enter keeps the value already in ENV_FILE."""
    current = _existing(key)
    hint = f" {DIM}[Enter keeps current]{RESET}" if current else ""
    answer = input(f"  {BOLD}{prompt}{RESET}{hint} ").strip()
    return answer or (current or "")


def ask_secret(key: str, prompt: str) -> str:
    """Like ask, but the input is hidden."""
    current = _existing(key)
    hint = " [Enter keeps current]" if current else ""
    answer = getpass.getpass(f"  {prompt}{hint} ").strip()
    return answer or (current or "")


def write_env(key: str, value: str) -> None:
    """Upsert KEY='VALUE' into ENV_FILE, replacing any existing line. Idempotent."""
    lines: list[str] = []
    if os.path.isfile(ENV_FILE):
        with open(ENV_FILE, encoding="utf-8") as handle:
            lines = [line for line in handle if not line.startswith(f"{key}=")]
    quoted = value.replace("'", "'\\''")
    lines.append(f"{key}='{quoted}'\n")
    directory = os.path.dirname(os.path.abspath(ENV_FILE))
    fd, tmp = tempfile.mkstemp(dir=directory)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.writelines(lines)
    if os.path.exists(ENV_FILE):
        shutil.copymode(ENV_FILE, tmp)
    else:
        os.chmod(tmp, 0o600)
    os.replace(tmp, ENV_FILE)
    WRITTEN_ENV.append(key)
    print(f"  {GREEN}✓ wrote{RESET} {key} → {ENV_FILE}")


def _gh_ready() -> bool:
    return bool(shutil.which("gh")) and subprocess.run(
        ["gh", "auth", "status"], capture_output=True
    ).returncode == 0


def set_secret(name: str, value: str) -> None:
    """Set a GitHub Actions repository secret with gh, or record it as still to do."""
    if _gh_ready() and subprocess.run(
        ["gh", "secret", "set", name], input=value, text=True, capture_output=True
    ).returncode == 0:
        WRITTEN_SECRET.append(name)
        print(f"  {GREEN}✓ set{RESET} GitHub secret {name}")
        return
    SKIPPED.append(f"GitHub secret {name} (set it by hand: gh secret set {name})")
    warn(f"skipped GitHub secret {name}: gh is not ready; set it later")


def set_var(name: str, value: str) -> None:
    """Set a GitHub Actions repository variable (not secret) with gh."""
    if _gh_ready() and subprocess.run(
        ["gh", "variable", "set", name, "--body", value], capture_output=True
    ).returncode == 0:
        print(f"  {GREEN}✓ set{RESET} GitHub variable {name}")
        return
    SKIPPED.append(f"GitHub variable {name}")
    warn(f"skipped GitHub variable {name}: gh is not ready; set it later")


def finish() -> None:
    """Clear, then summarise everything configured and everything left to do."""
    _clear()
    print(f"\n{BOLD}{GREEN}  ✓ Setup complete{RESET}")
    if WRITTEN_ENV:
        note(f"wrote {len(WRITTEN_ENV)} value(s) to {ENV_FILE}: {' '.join(WRITTEN_ENV)}")
    if WRITTEN_SECRET:
        note(f"set {len(WRITTEN_SECRET)} GitHub secret(s): {' '.join(WRITTEN_SECRET)}")
    if SKIPPED:
        print()
        warn("still to do by hand:")
        for item in SKIPPED:
            note(f"  - {item}")
    print()


# ──────────────────────────────────────────────────────────────────────────
