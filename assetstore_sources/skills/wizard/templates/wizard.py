# ──────────────────────────────────────────────────────────────────────────

def run_wizard() -> None:
    global TOTAL_STAGES
    TOTAL_STAGES = 1

    banner("Stripe setup")

    # ── Example stage: replace with your real steps ───────────────────────
    stage("Stripe: API keys")
    say("We'll grab your Stripe test keys and store them for local dev and CI.")
    open_url("https://dashboard.stripe.com/test/apikeys")
    step("On the API keys page, copy the Publishable key (starts pk_test_).")
    publishable = ask("STRIPE_PUBLISHABLE_KEY", "Paste the publishable key:")
    step("Click 'Reveal test key' on the Secret key row, then copy it.")
    secret = ask_secret("STRIPE_SECRET_KEY", "Paste the secret key:")
    write_env("STRIPE_PUBLISHABLE_KEY", publishable)
    write_env("STRIPE_SECRET_KEY", secret)
    set_secret("STRIPE_SECRET_KEY", secret)  # CI needs this one
    # ──────────────────────────────────────────────────────────────────────

    finish()


if __name__ == "__main__":
    try:
        run_wizard()
    except KeyboardInterrupt:
        print(f"\n{YELLOW}  Stopped. Run the wizard again to continue: saved values are kept.{RESET}")
        sys.exit(130)
